def should_process(path: Path) -> bool:
    """只处理允许的文件类型"""
    if path.suffix.lower() in {".html", ".md", ".js", ".json", ".css"}:
        return True
    return False


def clean_file(path: Path) -> tuple[int, int]:
    """清洗单个文件，返回 (替换次数, 总字符变化)"""
    try:
        content = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        try:
            content = path.read_text(encoding="gbk")
        except Exception:
            return 0, 0

    original = content
    total_changes = 0

    for old, new in RULES:
        if old in content:
            count = content.count(old)
            content = content.replace(old, new)
            total_changes += count

    if content != original:
        path.write_text(content, encoding="utf-8")
        return total_changes, len(content) - len(original)

    return 0, 0


def scan() -> list[Path]:
    """扫描所有应该处理的文件"""
    files = []
    for p in BASE.rglob("*"):
        if p.is_file() and should_process(p):
            # 排除 .workbuddy 等目录
            try:
                rel = p.relative_to(BASE)
                if any(part.startswith(".") and part != "." for part in rel.parts[:-1]):
                    continue
                if "node_modules" in rel.parts:
                    continue
            except ValueError:
                continue
            files.append(p)
    return files


