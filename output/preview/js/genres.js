// 工具函数：按 ID 找题材
window.getGenreById = function(id) {
  return GENRES_LIBRARY.find(g => g.id === id);
};

// 工具函数：自动匹配（基于小说文本+标题，得分最高→题材）
window.matchGenre = function(text, title='') {
  if (!text && !title) return null;
  const corpus = (title + '\n' + (text || '').slice(0, 5000)).toLowerCase();
  const scores = GENRES_LIBRARY.map(g => {
    let s = 0;
    for (const kw of g.keywords) {
      const re = new RegExp(kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
      const m = corpus.match(re);
      if (m) s += m.length * (kw.length >= 2 ? 2 : 1); // 长关键词加权
    }
    return { id: g.id, score: s };
  });
  scores.sort((a, b) => b.score - a.score);
  return scores[0].score > 0 ? { top: scores[0], second: scores[1], all: scores.filter(s => s.score > 0) } : null;
};

